import React, { useMemo } from "react";
import { StyleSheet, View } from "react-native";
import { WebView } from "react-native-webview";

import { ClinicMapProps } from "./ClinicMapBase";
import { buildClinicMapHtml } from "./ClinicMapHtml";
import colors from "../../design/tokens/colors";
import radius from "../../design/tokens/radius";

export default function ClinicMap({
  latitude,
  longitude,
  clinics,
  selectedClinicId,
  onSelectClinic,
}: ClinicMapProps) {
  const html = useMemo(
    () => buildClinicMapHtml({ latitude, longitude, clinics, selectedClinicId }),
    [latitude, longitude, clinics, selectedClinicId]
  );

  return (
    <View style={styles.wrapper}>
      <WebView
        source={{ html }}
        originWhitelist={["*"]}
        javaScriptEnabled
        domStorageEnabled
        cacheEnabled
        setSupportMultipleWindows={false}
        userAgent="DRHealthcareFYP/1.0 (OpenStreetMap clinic locator)"
        onMessage={(event) => {
          try {
            const message = JSON.parse(event.nativeEvent.data || "{}");
            if (message?.source !== "dr-clinic-map" || !message?.clinicId) return;
            const clinic = clinics.find((item) => item.id === message.clinicId);
            if (clinic) onSelectClinic?.(clinic);
          } catch {
            // Ignore messages that were not generated by our embedded map.
          }
        }}
      />
    </View>
  );
}

const styles = StyleSheet.create({
  wrapper: {
    height: 300,
    overflow: "hidden",
    borderRadius: radius.xl,
    borderWidth: 1,
    borderColor: colors.border,
    backgroundColor: colors.teal50,
  },
});
